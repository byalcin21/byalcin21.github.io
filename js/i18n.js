const text = (lang, key) => copy[lang][key] || copy.de[key] || "";

const setMeta = (selector, value) => {
  const node = document.querySelector(selector);
  if (node && value) node.setAttribute("content", value);
};

const applyLanguage = (lang) => {
  const active = lang === "en" ? "en" : "de";
  document.documentElement.lang = active;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = text(active, node.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    node.innerHTML = text(active, node.dataset.i18nHtml);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    node.setAttribute("aria-label", text(active, node.dataset.i18nAria));
  });

  document.title = text(active, "meta.title");
  setMeta('meta[name="description"]', text(active, "meta.description"));
  setMeta('meta[name="keywords"]', text(active, "meta.keywords"));
  setMeta('meta[property="og:title"]', text(active, "meta.title"));
  setMeta('meta[property="og:description"]', text(active, "meta.ogDescription"));
  setMeta('meta[property="og:locale"]', text(active, "meta.locale"));
  setMeta('meta[name="twitter:title"]', text(active, "meta.title"));
  setMeta('meta[name="twitter:description"]', text(active, "meta.ogDescription"));

  const cv = document.querySelector("[data-cv]");
  if (cv) {
    cv.href = `mailto:baran.ylcn21@gmail.com?subject=${encodeURIComponent(text(active, "contact.cv.subject"))}`;
  }

  const ld = document.getElementById("person-ld");
  if (ld) {
    const data = JSON.parse(ld.textContent);
    data.jobTitle = text(active, "meta.jobTitle");
    data.alumniOf.name = text(active, "edu.school");
    ld.textContent = JSON.stringify(data, null, 2);
  }

  document.querySelectorAll("[data-set-lang]").forEach((button) => {
    const on = button.dataset.setLang === active;
    button.classList.toggle("is-active", on);
    button.setAttribute("aria-pressed", String(on));
  });
};

const readLanguage = () => {
  const param = new URLSearchParams(location.search).get("lang");
  if (param === "en" || param === "de") return param;
  try {
    const stored = localStorage.getItem("portfolio-lang");
    if (stored === "en" || stored === "de") return stored;
  } catch (error) {
    return "de";
  }
  return "de";
};

const rememberLanguage = (lang) => {
  try {
    localStorage.setItem("portfolio-lang", lang);
  } catch (error) {
    /* private mode */
  }
  const url = new URL(location.href);
  if (lang === "de") url.searchParams.delete("lang");
  else url.searchParams.set("lang", "en");
  history.replaceState(null, "", url);
};

const closeMenu = () => {
  document.querySelector(".nav-links")?.classList.remove("is-open");
  document.body.classList.remove("nav-open");
  document.querySelector(".nav-toggle")?.setAttribute("aria-expanded", "false");
};

document.querySelectorAll("[data-set-lang]").forEach((button) => {
  button.addEventListener("click", () => {
    const lang = button.dataset.setLang === "en" ? "en" : "de";
    rememberLanguage(lang);
    applyLanguage(lang);
    closeMenu();
  });
});

applyLanguage(readLanguage());
